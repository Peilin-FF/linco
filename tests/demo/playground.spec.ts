test('mobile navigation and static search content remain available', async ({ page, browser, baseURL }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(391)
  const context = await browser.newContext({ javaScriptEnabled: false })
  const staticPage = await context.newPage()
  await staticPage.goto(baseURL!)
  await expect(staticPage.getByRole('heading', { level: 1 })).toContainText('Keep the vibe.')
  await expect(staticPage.getByRole('heading', { name: 'A landing page for your side project' })).toBeVisible()
  expect(await staticPage.locator('script[type="application/ld+json"]').textContent()).toContain('SoftwareApplication')
  await context.close()
})
