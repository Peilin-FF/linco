test('history resume explains the restart and cancel does not interrupt an agent', async ({ page }) => {
  await openWorkbench(page)
  await page.locator('#agent-composer').fill('Keep this draft until I resume')
  const starts = () => page.evaluate(() => (window as any).__workbench.calls.filter((call: any) => call.cmd === 'term_start').length)
  const before = await starts()
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  const history = page.locator('.sidebar-history')
  await history.getByRole('button', { name: /Build the project workspace/ }).click()
  await expect(history.getByText('This restarts the agent', { exact: false })).toBeVisible()
  await history.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(await starts()).toBe(before)
  await history.getByRole('button', { name: /Build the project workspace/ }).click()
  await history.getByRole('button', { name: 'Resume conversation', exact: true }).click()
  await expect.poll(starts).toBe(before + 1)
  await expect(page.locator('.workspace-drawer')).toHaveCount(0)
  await expect(page.locator('#agent-composer')).toHaveValue('')
})

test('the message box grows, scrolls long drafts, and leaves room for the terminal', async ({ page }) => {
  await page.setViewportSize({ width: 1000, height: 650 })
  const errors = await openWorkbench(page)
  const input = page.locator('#agent-composer')
  const initial = (await input.boundingBox())!.height
  expect(initial).toBeGreaterThanOrEqual(104)
  await page.getByRole('separator', { name: 'Resize message box', exact: true }).press('ArrowUp')
  expect((await input.boundingBox())!.height).toBeGreaterThan(initial)
  const draft = Array.from({ length: 30 }, (_, i) => `Research step ${i + 1}: keep this entire line.`).join('\n')
  await input.fill(draft)
  await expect(input).toHaveValue(draft)
  await expect(input).toHaveCSS('overflow-y', 'auto')
  expect((await input.boundingBox())!.height).toBeGreaterThan(initial + 40)
  const terminal = await page.locator('[data-terminal-kind="chat"]:visible').boundingBox()
  const composer = await page.locator('.pane-composer').boundingBox()
  expect(terminal!.y + terminal!.height).toBeLessThanOrEqual(composer!.y)
  expect(terminal!.height).toBeGreaterThan(200)
  await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  await expect(input).toHaveValue(draft)
  await input.press('ArrowUp')
  await expect(input).toHaveValue(draft)
  await page.screenshot({ path: 'artifacts/composer-expanded.png' })
  expect(errors).toEqual([])
})

