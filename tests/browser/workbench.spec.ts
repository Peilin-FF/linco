async function openWorkbench(page: Page, query = '') {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto(`/tests/browser/workbench.html${query}`)
  await expect(page.getByRole('navigation', { name: 'Workspaces', exact: true })).toBeVisible({ timeout: 15000 })
  await expect(page.locator('.workspace-canvas')).toBeVisible()
  return errors
}

async function assertFits(page: Page) {
  const bounds = await page.evaluate(() => {
    const selectors = ['.workbench-content', '.workspace-canvas']
    return selectors.map((selector) => {
      const rect = document.querySelector(selector)!.getBoundingClientRect()
      return { selector, x: rect.x, right: rect.right, bottom: rect.bottom, width: rect.width, height: rect.height, viewport: [innerWidth, innerHeight] }
    })
  })
  for (const rect of bounds) {
    expect(rect.x, rect.selector).toBeGreaterThanOrEqual(0)
    expect(rect.right, rect.selector).toBeLessThanOrEqual(rect.viewport[0] + 1)
    expect(rect.bottom, rect.selector).toBeLessThanOrEqual(rect.viewport[1] + 1)
    expect(rect.height, rect.selector).toBeGreaterThan(40)
  }
}

