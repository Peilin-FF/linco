test('an uncertain creation keeps the draft visible and is never retried automatically', async ({ page }) => {
  await open(page, '?notion-write-error')
  await page.getByRole('button', { name: 'Templates', exact: true }).click()
  await page.getByRole('button', { name: 'Create project notebook', exact: true }).click()
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('Keep this draft')
  await page.getByRole('button', { name: 'Create in Notion', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Check Notion before retrying')
  await expect(page.getByRole('textbox', { name: 'Title', exact: true })).toHaveValue('Keep this draft')
  const recordCalls = (await calls(page, 'notion_tool')).filter((call: any) => call.args.arguments.parent?.data_source_id)
  expect(recordCalls).toHaveLength(1)
})

