import { expect, test, type Page } from '@playwright/test'

const pageUrl = 'https://www.notion.so/0123456789abcdef0123456789abcdef'
const calls = (page: Page, cmd: string) => page.evaluate((name) => (window as any).__workbench.calls.filter((c: any) => c.cmd === name), cmd)
const visible = async (page: Page) => (await calls(page, 'notion_layout')).at(-1)?.args.visible
async function open(page: Page, query = '') {
  await page.goto(`/tests/browser/workbench.html${query}`)
  await page.getByRole('button', { name: 'Notes', exact: true }).click()
}

test('native Notes is lazy, fits beside the agent, and hides for modes and overlays', async ({ page }) => {
  await page.goto('/tests/browser/workbench.html')
  await expect(page.getByRole('button', { name: 'Notes', exact: true })).toBeVisible()
  expect(await calls(page, 'notion_open')).toHaveLength(0)
  await page.getByRole('button', { name: 'Notes', exact: true }).click()
  await expect.poll(() => visible(page)).toBe(true)
  const layout = (await calls(page, 'notion_layout')).at(-1).args.bounds
  const agent = await page.locator('.pane-composer').boundingBox()
  expect(layout.x).toBeGreaterThanOrEqual(agent!.x + agent!.width)
  expect(layout.height).toBeGreaterThan(500)
  await expect(page.locator('[data-workspace-view="notion"] iframe')).toHaveCount(0)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect.poll(() => visible(page)).toBe(false)
  await page.locator('.settings-sidebar').getByRole('button').first().click()
  await expect.poll(() => visible(page)).toBe(true)
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await expect.poll(() => visible(page)).toBe(false)
  await page.getByRole('button', { name: 'Close projects', exact: true }).click()
  await expect.poll(() => visible(page)).toBe(true)
  await page.getByRole('button', { name: 'Code', exact: true }).click()
  await expect.poll(() => visible(page)).toBe(false)
  const count = (await calls(page, 'notion_open')).length
  await page.getByRole('button', { name: 'Vibe Working', exact: true }).click()
  await expect.poll(() => visible(page)).toBe(true)
  expect(await calls(page, 'notion_open')).toHaveLength(count)
  await page.setViewportSize({ width: 900, height: 600 })
  await expect.poll(async () => (await calls(page, 'notion_layout')).at(-1).args.bounds.height).toBeLessThan(520)
})

test('links a project persistently and shares canonical read-only context only after confirmation', async ({ page }) => {
  await open(page)
  await expect(page.getByRole('button', { name: 'Use in agent', exact: true })).toBeDisabled()
  await page.getByRole('textbox', { name: 'Notion page URL' }).fill(`${pageUrl}?token=private`)
  await page.getByRole('textbox', { name: 'Notion page URL' }).press('Enter')
  await expect(page.getByRole('button', { name: 'Link this page to the project' })).toBeEnabled()
  await page.getByRole('button', { name: 'Link this page to the project' }).click()
  await expect(page.getByText('Project notebook linked', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Notes', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Notion page URL' })).toHaveValue(pageUrl)
  await page.getByRole('button', { name: 'Use in agent', exact: true }).click()
  await expect.poll(() => visible(page)).toBe(false)
  expect((await calls(page, 'term_write')).some((c: any) => c.args.data.includes(pageUrl))).toBe(false)
  await page.getByRole('button', { name: 'Read with agent', exact: true }).click()
  await expect.poll(async () => (await calls(page, 'term_write')).some((c: any) => c.args.data.includes('Do not change the note yet'))).toBe(true)
  expect((await calls(page, 'term_write')).some((c: any) => c.args.data.includes('token=private'))).toBe(false)
})

test('rejects unsafe links and explains MCP separately without executing setup', async ({ page }) => {
  await open(page)
  const initial = (await calls(page, 'notion_open')).length
  await page.getByRole('textbox', { name: 'Notion page URL' }).fill('https://notion.so.evil.test/')
  await page.getByRole('textbox', { name: 'Notion page URL' }).press('Enter')
  await expect(page.getByRole('alert')).toContainText('Enter an HTTPS link')
  expect(await calls(page, 'notion_open')).toHaveLength(initial)
  await page.getByRole('button', { name: 'Connect Codex', exact: true }).click()
  await expect.poll(() => visible(page)).toBe(false)
  await expect(page.getByRole('heading', { name: 'One notebook. You and Codex.' })).toBeVisible()
  expect((await calls(page, 'term_write')).some((c: any) => c.args.data.includes('mcp add'))).toBe(false)
  await page.getByRole('button', { name: 'Back to the notebook' }).click()
  await expect.poll(() => visible(page)).toBe(true)
})

