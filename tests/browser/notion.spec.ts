test('sets up an editable notebook and creates a template record without asking the agent', async ({ page }) => {
  await open(page)
  await expect(page.getByRole('button', { name: 'Local · connected', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Templates', exact: true }).click()
  await expect.poll(() => visible(page)).toBe(false)
  await expect(page.getByRole('dialog')).toContainText('Your project notebook')
  expect(await calls(page, 'notion_tool')).toHaveLength(0)
  await page.getByRole('button', { name: 'Create project notebook', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Start a new note' })).toBeVisible()
  await page.getByRole('button', { name: 'Experiment A reproducible test' }).click()
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('Linco revision · first trial')
  await page.getByRole('textbox', { name: 'Starting note · optional', exact: true }).fill('Test whether progress and feedback are easier to follow.')
  await page.screenshot({ path: 'artifacts/notion-template-picker.png' })
  await page.getByRole('button', { name: 'Create in Notion', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect.poll(() => visible(page)).toBe(true)
  const writes = (await calls(page, 'notion_tool')).filter((call: any) => call.args.tool === 'notion-create-pages')
  const record = writes.at(-1).args.arguments
  expect(record.pages[0].properties.Status).toBe('Draft')
  expect(record.pages[0].content).toContain('Test whether progress')
  expect(record.pages[0].content).toContain('## Run log')
  expect((await calls(page, 'term_write')).some((call: any) => call.args.data.includes('first trial'))).toBe(false)
  await page.getByRole('button', { name: 'Use in agent', exact: true }).click()
  await page.getByRole('textbox', { name: 'Your feedback or question · optional' }).fill('Please review the acceptance criteria.')
  await page.getByRole('button', { name: 'Read with agent', exact: true }).click()
  await expect.poll(async () => (await calls(page, 'term_write')).some((call: any) => call.args.data.includes('Please review the acceptance criteria.'))).toBe(true)
  expect((await calls(page, 'term_write')).some((call: any) => call.args.data.includes('## Run log'))).toBe(true)
})

test('template picker stays compact at small sizes and adapts to dark mode', async ({ page }) => {
  await open(page, '?theme=linco-dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme-dark', '1')
  await page.getByRole('button', { name: 'Templates', exact: true }).click()
  await page.getByRole('button', { name: 'Create project notebook', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Start a new note' })).toBeVisible()
  await page.setViewportSize({ width: 900, height: 600 })
  const bounds = await page.getByRole('dialog').boundingBox()
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(600)
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('A compact notebook')
  await expect(page.getByRole('button', { name: 'Create in Notion', exact: true })).toBeInViewport()
  await page.screenshot({ path: 'artifacts/notion-template-picker-dark.png' })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect.poll(() => visible(page)).toBe(true)
})

