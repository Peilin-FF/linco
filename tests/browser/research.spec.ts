import { expect, test, type Page } from '@playwright/test'

const calls = (page: Page, cmd: string) => page.evaluate(name => (window as any).__workbench.calls.filter((call: any) => call.cmd === name), cmd)
async function open(page: Page, extra = '') {
  await page.goto(`/tests/browser/workbench.html?research${extra}`)
  await page.getByRole('button', { name: 'Notes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your research projects' })).toBeVisible()
  await page.getByRole('button', { name: /Memory study.*Can a new agent/ }).click()
  await expect(page.getByRole('button', { name: 'Baseline exploration Inspect the log before drawing a conclusion.' })).toBeVisible()
}

test('project tabs isolate module records and native Notion stays hidden', async ({ page }) => {
  await open(page)
  await expect(page.getByText('Private reading-project note', { exact: true })).toHaveCount(0)
  expect((await calls(page, 'notion_layout')).at(-1).args.visible).toBe(false)
  await page.getByRole('navigation', { name: 'Project modules' }).getByRole('button', { name: 'Milestones', exact: true }).click()
  await expect(page.getByRole('button', { name: /Reproduce the baseline A rerunnable/ })).toBeVisible()
  await expect(page.getByText('Compare annotation workflows', { exact: true })).toHaveCount(0)
  const tops = await page.locator('.research-milestone-board > section').evaluateAll(nodes => nodes.map(node => Math.round(node.getBoundingClientRect().top)))
  expect(new Set(tops).size).toBe(1)
  await page.screenshot({ path: 'artifacts/research-project-milestones.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Back to all projects' }).click()
  await page.getByRole('button', { name: /Reading tools.*How can annotations/ }).click()
  await expect(page.getByText('Private reading-project note', { exact: true })).toBeVisible()
  await expect(page.getByText('Baseline exploration', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Memory study', exact: true }).click()
  await expect(page.getByText('Baseline exploration', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Memory study', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Reading tools', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.screenshot({ path: 'artifacts/research-project-overview.png', animations: 'disabled' })
})

