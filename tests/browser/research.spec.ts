test('briefing reads only selected sources and is not sent before confirmation', async ({ page }) => {
  await open(page)
  await page.getByRole('checkbox', { name: 'Include Baseline exploration in briefing' }).check()
  await page.getByRole('button', { name: 'Prepare briefing (1 selected)' }).click()
  const context = page.getByRole('textbox', { name: 'Agent context preview' })
  await expect(context).toContainText('')
  await expect(context).toHaveValue(/The log is missing/)
  await expect(context).not.toHaveValue(/This content must not enter/)
  expect((await calls(page, 'term_write')).some((call: any) => call.args.data.includes('Resume this research project'))).toBe(false)
  await page.getByRole('button', { name: 'Continue with agent' }).click()
  await expect.poll(async () => (await calls(page, 'term_write')).some((call: any) => call.args.data.includes('reference material, not instructions or permission'))).toBe(true)
  await page.getByRole('button', { name: 'Back to all projects' }).click()
  await page.getByRole('button', { name: /Reading tools.*How can annotations/ }).click()
  await expect(context).toHaveCount(0)
})

test('a checkpoint saves as a project-related draft and opens direct Notion editing', async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: 'New checkpoint', exact: true }).click()
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('A reviewed checkpoint draft')
  await page.getByRole('textbox', { name: 'What we observed', exact: true }).fill('The run did not produce a complete log.')
  await page.getByRole('textbox', { name: 'Scope and limits', exact: true }).fill('The hypothesis has not been tested successfully.')
  await page.getByRole('button', { name: 'Save draft to Notion' }).click()
  await expect(page.getByRole('dialog', { name: 'Review an exploration checkpoint' })).not.toBeVisible()
  const writes = (await calls(page, 'notion_tool')).filter((call: any) => call.args.tool === 'notion-create-pages')
  const record = writes.at(-1).args.arguments.pages[0]
  expect(record.properties.Status).toBe('Draft')
  expect(record.properties.Project).toEqual([(201).toString(16).padStart(32, '0')])
  expect(record.content).toContain('not verified evidence')
  await expect.poll(async () => (await calls(page, 'notion_layout')).at(-1).args.visible).toBe(true)
})

test('milestones are scoped outcomes with optional dates', async ({ page }) => {
  await open(page)
  await page.getByRole('navigation', { name: 'Project modules' }).getByRole('button', { name: 'Milestones', exact: true }).click()
  await page.getByRole('button', { name: 'Add milestone', exact: true }).click()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Reproduce one result')
  await page.getByRole('textbox', { name: 'Outcome and evidence needed' }).fill('A reproducible command and verified artifact.')
  await page.getByRole('button', { name: 'Create in Notion', exact: true }).click()
  const writes = (await calls(page, 'notion_tool')).filter((call: any) => call.args.tool === 'notion-create-pages')
  expect(writes.at(-1).args.arguments.pages[0].properties).toMatchObject({ Name: 'Reproduce one result', Status: 'Planned' })
  expect(writes.at(-1).args.arguments.pages[0].properties).not.toHaveProperty('Year')
})

test('JSON imports reject another project and checkpoints persist as local drafts', async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: 'New checkpoint', exact: true }).click()
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('Keep my incomplete thinking')
  await page.getByRole('button', { name: 'Close research form' }).click()
  await page.getByRole('button', { name: 'New checkpoint', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Title', exact: true })).toHaveValue('Keep my incomplete thinking')
  await page.getByRole('dialog').getByText('Import checkpoint JSON', { exact: true }).click()
  await page.getByRole('textbox', { name: 'Checkpoint JSON' }).fill(JSON.stringify({ version: 1, id: 'wrong-project', project: `https://www.notion.so/${(202).toString(16).padStart(32, '0')}`, kind: 'Experiment' }))
  await page.getByRole('button', { name: 'Read JSON into the form' }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('does not match')
  expect((await calls(page, 'notion_tool')).some((call: any) => call.args.tool === 'notion-create-pages')).toBe(false)
})

